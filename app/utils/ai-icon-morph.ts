/** Keyframes in one loop: the icon, the circle, the flower, then back to the icon. */
export const AI_ICON_KEYFRAMES = KEYFRAMES.length

const round = (value: number) => Math.round(value * 100) / 100
const mix = (from: number, to: number, t: number) => from + (to - from) * t
const smooth = (t: number) => t * t * (3 - 2 * t)

function blend(from: Keyframe, to: Keyframe, t: number): AiIconFrame {
  const m = (a: number, b: number) => round(mix(a, b, t))
  const mask = from.mask.map((value, index) => m(value, to.mask[index]!))
  return {
    mask: `M${mask[0]} ${mask[1]}C${mask.slice(2).join(" ")}Z`,
    blur: m(from.blur, to.blur),
    tint: m(from.tint, to.tint),
    wash: m(from.wash, to.wash),
    blobs: from.blobs.map((a, index) => {
      const b = to.blobs[index]!
      const [r, g, bl] = a.color.map((channel, i) => Math.round(mix(channel, b.color[i]!, t)))
      return {
        x: m(a.x, b.x),
        y: m(a.y, b.y),
        width: m(a.width, b.width),
        height: m(a.height, b.height),
        rx: m(a.rx, b.rx),
        ry: m(a.ry, b.ry),
        fill: `rgb(${r}, ${g}, ${bl})`,
        "fill-opacity": m(a.opacity, b.opacity),
      }
    }),
  }
}

const REST_FRAME: AiIconFrame = { ...blend(KEYFRAMES[0]!, KEYFRAMES[0]!, 0), mask: REST_MASK }

/**
 * The icon at `phase`: a whole number is a keyframe, the fraction between two is the morph towards the next
 * one, eased so each shape settles briefly before it moves on. Phase 0 is the supplied artwork itself.
 */
export function sampleAiIcon(phase: number): AiIconFrame {
  if (phase === 0) return REST_FRAME
  const index = Math.floor(phase)
  return blend(
    KEYFRAMES[index % AI_ICON_KEYFRAMES]!,
    KEYFRAMES[(index + 1) % AI_ICON_KEYFRAMES]!,
    smooth(phase - index),
  )
}
