export interface AiIconFrame {
  mask: string
  blur: number
  /** Opacity of the yellow wash over the white base. */
  tint: number
  /** Opacity of the blue-to-cyan gradient over the white base. */
  wash: number
  blobs: AiIconBlob[]
}

type Rgb = [number, number, number]

interface KeyBlob {
  x: number
  y: number
  width: number
  height: number
  rx: number
  ry: number
  color: Rgb
  opacity: number
}

interface Keyframe {
  mask: number[]
  blur: number
  tint: number
  wash: number
  /** Always three, in the same colour role in every keyframe, so each one has a partner to morph into. */
  blobs: KeyBlob[]
}

